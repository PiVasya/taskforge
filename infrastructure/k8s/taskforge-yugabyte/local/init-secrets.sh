#!/usr/bin/env bash
set -Eeuo pipefail

# Fail closed if this kubeconfig points outside the dedicated LOCAL K3s.
"$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)/guard-local-context.sh"
[[ "${TASKFORGE_LOCAL_K3S_ACK:-}" == local-development-only ]] || { echo 'local only' >&2; exit 2; }
for cmd in kubectl openssl; do command -v "$cmd" >/dev/null || { echo "Missing $cmd" >&2; exit 2; }; done
umask 077
BASE="${HOME}/.config/taskforge-k3s-lab"
mkdir -p "$BASE"
FILE="$BASE/credentials.env"
if [[ ! -e "$FILE" ]]; then
  { printf 'JWT_KEY=%s\n' "$(openssl rand -hex 48)"
    printf 'INTERNAL_KEY=%s\n' "$(openssl rand -hex 32)"
    printf 'REDIS_PASSWORD=%s\n' "$(openssl rand -hex 24)"
    printf 'RABBITMQ_PASSWORD=%s\n' "$(openssl rand -hex 24)"
    printf 'MINIO_ROOT_PASSWORD=%s\n' "$(openssl rand -hex 32)"
  } > "$FILE"
  chmod 600 "$FILE"
fi
# The file is generated by this script, not sourced as executable shell content.
# Avoid passing secrets as CLI options or logging them.
read_value(){ sed -n "s/^${1}=//p" "$FILE" | head -n 1; }
JWT="$(read_value JWT_KEY)"; INTERNAL="$(read_value INTERNAL_KEY)"; REDIS="$(read_value REDIS_PASSWORD)"
RABBIT="$(read_value RABBITMQ_PASSWORD)"; MINIO="$(read_value MINIO_ROOT_PASSWORD)"
for var in "$JWT" "$INTERNAL" "$REDIS" "$RABBIT" "$MINIO"; do [[ -n "$var" ]] || { echo 'Corrupt local credentials file' >&2; exit 2; }; done
kubectl get ns taskforge-k3s-lab >/dev/null 2>&1 || kubectl create namespace taskforge-k3s-lab
kubectl label namespace taskforge-k3s-lab taskforge.io/use=k3s-isolated-lab --overwrite >/dev/null
TMP="$(mktemp -d)"; chmod 700 "$TMP"; trap 'rm -rf "$TMP"' EXIT
cat > "$TMP/app.env" <<CFG
Jwt__Key=$JWT
Jwt__SigningKey=$JWT
InternalApi__Key=$INTERNAL
TaskForgeInternalApi__ApiKey=$INTERNAL
TaskForge__InternalKey=$INTERNAL
ConnectionStrings__Redis=redis:6379,password=$REDIS,abortConnect=false
Redis__ConnectionString=redis:6379,password=$REDIS,abortConnect=false
RabbitMq__Password=$RABBIT
REDIS_PASSWORD=$REDIS
RABBITMQ_PASSWORD=$RABBIT
MINIO_ROOT_PASSWORD=$MINIO
S3__AccessKey=taskforge
S3__SecretKey=$MINIO
CFG
kubectl -n taskforge-k3s-lab create secret generic taskforge-app-secrets --from-env-file="$TMP/app.env" --dry-run=client -o yaml | kubectl apply -f - >/dev/null
# No authentication/TLS in the SINGLE-NODE Yugabyte lab. The password below is
# deliberately dummy (YSQL's auth is disabled), not a production credential.
DBS=(identity education content tasks solutions execution ai support minecraft files notifications observability)
for svc in "${DBS[@]}"; do
  printf '%s-api=Host=taskforge-k3s-lab-yb-yb-tservers.taskforge-k3s-lab-db.svc.cluster.local;Port=5433;Database=taskforge_k3s_%s;Username=yugabyte;Password=local-only-not-authenticated;SSL Mode=Disable;Timeout=10;Command Timeout=90\n' "$svc" "$svc" >> "$TMP/db.env"
done
printf 'rating-worker=Host=taskforge-k3s-lab-yb-yb-tservers.taskforge-k3s-lab-db.svc.cluster.local;Port=5433;Database=taskforge_k3s_solutions;Username=yugabyte;Password=local-only-not-authenticated;SSL Mode=Disable;Timeout=10;Command Timeout=90\n' >> "$TMP/db.env"
printf 'telegram-quiz-bot=Host=taskforge-k3s-lab-yb-yb-tservers.taskforge-k3s-lab-db.svc.cluster.local;Port=5433;Database=taskforge_k3s_telegram_quiz;Username=yugabyte;Password=local-only-not-authenticated;SSL Mode=Disable;Timeout=10;Command Timeout=90\n' >> "$TMP/db.env"
# Kubernetes Secret data keys may contain hyphens; --from-env-file parses them as
# shell env names and is not portable, so use file keys instead.
source_keys=()
while IFS='=' read -r key value; do
  [[ -n "$key" && -n "$value" ]] || continue
  printf '%s' "$value" > "$TMP/$key"
  source_keys+=("--from-file=$key=$TMP/$key")
done < "$TMP/db.env"
kubectl -n taskforge-k3s-lab create secret generic taskforge-db-connections "${source_keys[@]}" --dry-run=client -o yaml | kubectl apply -f - >/dev/null
echo 'Local Kubernetes Secrets created/updated. Persistent local passwords: ~/.config/taskforge-k3s-lab/credentials.env (mode 600).'
